"""เช็คว่า King บนกระดานที่รับมากำลังโดนหมากฝ่ายตรงข้ามจ่ออยู่หรือไม่

หมากที่รองรับ: K (King), Q (Queen), B (Bishop), R (Rook), P (Pawn)
ตัวอักษรอื่นทั้งหมดนับเป็นช่องว่าง

แนวคิดหลัก: ยืนที่ King แล้วมองออกไปทั้ง 8 ทิศ เจอหมากตัวแรกในทิศไหน
ก็ดูว่าหมากตัวนั้นเดินมาถึงเราได้ไหม วิธีนี้ทำให้กฎ "หมากกินได้แค่ตัวแรก
ที่ขวางทางอยู่" ถูกต้องเองโดยอัตโนมัติ เพราะเจอตัวแรกแล้วเราหยุดทันที

ดูคำอธิบายฉบับเต็มได้ที่ EXPLAIN.md
"""

# ตัวอักษรที่นับว่าเป็นหมาก ใช้ตอบคำถามว่า "ช่องนี้มีอะไรขวางอยู่ไหม"
PIECES = "KQBRP"

# ก้าวเดินหนึ่งก้าวในรูป (row_step, col_step)
# row เพิ่ม = ลงล่าง, col เพิ่ม = ไปขวา

# ทิศทแยง 4 ทิศ ใช้กับ Bishop, Queen (และ Pawn ที่ระยะ 1)
DIAGONALS = ((-1, -1), (-1, 1), (1, -1), (1, 1))

# ทิศตรง 4 ทิศ ใช้กับ Rook, Queen
STRAIGHTS = ((-1, 0), (1, 0), (0, -1), (0, 1))


def parse_board(board):
    """แปลงข้อความกระดานให้เป็นลิสต์ของแถว พร้อมตรวจว่ากระดานใช้ได้จริงไหม

    เป็นด่านกรองก่อนเข้าสู่การคำนวณ ถ้าผ่านด่านนี้ไปได้แปลว่ากระดาน
    เชื่อถือได้แล้ว ฟังก์ชันอื่นจึงไม่ต้องเช็คอะไรซ้ำอีก

    รับ:  board - ข้อความกระดาน แต่ละแถวคั่นด้วยการขึ้นบรรทัดใหม่
    คืน:  ลิสต์ของข้อความ (แถวละตัว) ถ้ากระดานใช้ได้
          None ถ้ากระดานใช้ไม่ได้

    กระดานถือว่าใช้ไม่ได้เมื่อ: ไม่ใช่ข้อความ / ว่างเปล่า /
    แถวยาวไม่เท่ากัน / ไม่เป็นสี่เหลี่ยมจัตุรัส / ไม่มี King หรือมีเกิน 1 ตัว

    ตัวอย่าง: "R...\\n.K..\\n..P.\\n...." -> ["R...", ".K..", "..P.", "...."]
    """
    # ด่านแรก ถ้าไม่ใช่ข้อความก็จบ ไม่งั้นบรรทัดถัดไปจะพังด้วย AttributeError
    if not isinstance(board, str):
        return None

    # จัดรูปแบบการขึ้นบรรทัดให้เป็นแบบเดียวกัน กันไฟล์ที่แก้มาจาก Windows
    # ถ้าปล่อยให้ \r ติดท้ายแถว ความยาวแถวจะเพี้ยนไป 1 ตัว
    rows = board.replace("\r\n", "\n").replace("\r", "\n").split("\n")

    # ตัดบรรทัดว่างหัวท้ายทิ้ง เผื่อข้อความกระดานเขียนแบบ """ ขึ้นบรรทัดใหม่เลย
    # โดยไม่มีแบ็กสแลชปิดท้าย ซึ่งจะได้บรรทัดว่างแถมมาหัวหรือท้าย
    # บรรทัดว่างยาว 0 ตัวอักษร จึงเป็นส่วนหนึ่งของกระดานจัตุรัสไม่ได้อยู่แล้ว
    while rows and rows[-1] == "":
        rows.pop()
    while rows and rows[0] == "":
        rows.pop(0)

    if not rows:
        return None

    size = len(rows[0])
    if size == 0:
        return None

    # ทุกแถวต้องยาวเท่ากัน ไม่งั้นกระดานเป็นฟันปลา
    if any(len(row) != size for row in rows):
        return None

    # จำนวนแถวต้องเท่ากับความยาวแถว นี่คือความหมายของ "จัตุรัส"
    if len(rows) != size:
        return None

    # ต้องมี King เพียงตัวเดียว ไม่มีเลยก็ไม่รู้จะเช็คอะไร มีสองตัวก็ผิดกติกา
    if sum(row.count("K") for row in rows) != 1:
        return None

    return rows


def find_king(board):
    """หาว่า King อยู่ช่องไหนบนกระดาน

    รับ:  board - กระดานที่ผ่าน parse_board มาแล้ว
    คืน:  คู่ (แถว, คอลัมน์) ของช่องที่มี K
          None ถ้าหาไม่เจอ (ในทางปฏิบัติจะไม่เกิด เพราะ parse_board
          การันตีมาแล้วว่ามี King อยู่ 1 ตัว)
    """
    for row in range(len(board)):
        for col in range(len(board[row])):
            if board[row][col] == "K":
                return row, col
    return None


def first_piece_on_path(board, row, col, row_step, col_step):
    """เดินจากช่องที่กำหนดไปทางเดียวเรื่อยๆ แล้วบอกว่าเจอหมากตัวแรกเป็นอะไร

    เป็นหัวใจของไฟล์นี้ เพราะกฎ "หมากกินได้แค่ตัวแรกที่ขวางทางอยู่"
    เกิดขึ้นเองจากการที่เราหยุดทันทีที่เจอหมาก ไม่ต้องเขียนเงื่อนไขแยก

    รับ:  board     - กระดาน
          row, col  - ช่องที่เริ่มเดิน (ตัวช่องนี้ไม่ถูกนับ)
          row_step  - ขยับแถวครั้งละกี่ช่อง (-1 ขึ้นบน, +1 ลงล่าง, 0 อยู่กับที่)
          col_step  - ขยับคอลัมน์ครั้งละกี่ช่อง (-1 ไปซ้าย, +1 ไปขวา, 0 อยู่กับที่)
    คืน:  คู่ (ตัวอักษรของหมาก, ระยะห่างเป็นช่อง) ถ้าเจอหมาก
          คู่ (None, 0) ถ้าเดินจนหลุดขอบกระดานโดยไม่เจออะไร

    ที่ต้องคืนระยะห่างมาด้วยเพราะ Pawn กินได้แค่ระยะ 1 ช่อง
    ส่วนหมากอื่นกินได้ทุกระยะ ถ้าไม่รู้ระยะก็แยกสองกรณีนี้ไม่ออก

    ตัวอย่าง: กระดาน "R.PK" เริ่มที่ K มองไปทางซ้าย จะคืน ("P", 1)
    ไม่ใช่ ("R", 3) เพราะเรือถูกเบี้ยบังอยู่
    """
    size = len(board)
    distance = 1
    while True:
        next_row = row + row_step * distance
        next_col = col + col_step * distance

        # ออกนอกกระดานแล้ว แปลว่าทิศนี้ไม่มีหมากเลย
        # เงื่อนไขนี้ยังทำให้ while True จบเสมอ ไม่วนไม่รู้จบ
        # เพราะทุกทิศเดินออกจากจุดเริ่มต้น จึงหลุดขอบภายใน size รอบ
        if not (0 <= next_row < size and 0 <= next_col < size):
            return None, 0

        square = board[next_row][next_col]

        # ตัวอักษรที่ไม่ใช่หมากนับเป็นช่องว่าง เดินผ่านไปได้
        if square in PIECES:
            return square, distance

        distance += 1


def is_in_check(board):
    """ตัดสินว่า King กำลังโดนหมากฝ่ายตรงข้ามจ่ออยู่หรือไม่

    ทำงานโดยยืนที่ King แล้วมองออกไปทั้ง 8 ทิศ ทิศละครั้ง
    เจอหมากตัวแรกในทิศไหนก็ดูว่าหมากชนิดนั้นเดินมาถึงเราได้ไหม

    รับ:  board - กระดานที่ผ่าน parse_board มาแล้ว
    คืน:  True ถ้าโดนจ่อ, False ถ้าปลอดภัย
    """
    king_row, king_col = find_king(board)

    # แนวทแยง: Bishop กับ Queen กินได้ทุกระยะ ส่วน Pawn กินได้แค่ระยะ 1
    for row_step, col_step in DIAGONALS:
        piece, distance = first_piece_on_path(board, king_row, king_col, row_step, col_step)

        # ทิศนี้ว่างจนหลุดขอบ ข้ามไปดูทิศถัดไป
        # ต้องเช็คก่อนเทียบตัวอักษร ไม่งั้นจะเอา None ไปเทียบ
        if piece is None:
            continue

        if piece == "B" or piece == "Q":
            return True

        # เบี้ยกินเฉียงขึ้นบนระยะเดียวเท่านั้น (ความเป็นเส้นทแยงมาจากลูปนี้อยู่แล้ว)
        # row_step == 1 คือคัดเอาเฉพาะทิศทแยงล่าง เพราะเบี้ยที่อยู่ทแยงล่างของเรา
        # คือตัวที่กินเฉียงขึ้นมาโดนเราได้พอดี ส่วนเบี้ยที่อยู่ทแยงบนกินลงล่างไม่ได้
        if piece == "P" and distance == 1 and row_step == 1:
            return True

    # แนวตรง: Rook กับ Queen กินได้ทุกระยะ จึงไม่ต้องสนระยะห่าง
    for row_step, col_step in STRAIGHTS:
        piece, distance = first_piece_on_path(board, king_row, king_col, row_step, col_step)
        if piece == "R" or piece == "Q":
            return True

    # ครบทั้ง 8 ทิศแล้วไม่มีใครถึงตัว
    return False


def checkmate(board):
    """ประตูหน้าของโปรแกรม ตัวที่ main.py เรียกใช้

    พิมพ์ "Success" ถ้า King โดนจ่อ ไม่งั้นพิมพ์ "Fail" แล้วขึ้นบรรทัดใหม่

    รับ:  board - ข้อความกระดาน
    คืน:  ไม่คืนค่า (ผลลัพธ์ออกทางหน้าจอ)

    ถ้ากระดานใช้ไม่ได้จะไม่พิมพ์อะไรเลยแล้วคืนการควบคุมกลับไป ตามที่โจทย์
    อนุญาตให้เลือกระหว่าง "คืน error message" กับ "ไม่พิมพ์อะไรและคืนการควบคุม"
    ที่เลือกแบบไม่พิมพ์เพราะปลอดภัยกว่าตอนกรรมการเทียบผลลัพธ์
    """
    chess_board = parse_board(board)
    if chess_board is None:
        return
    print("Success" if is_in_check(chess_board) else "Fail")
